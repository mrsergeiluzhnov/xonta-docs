export const slugOf = (tool) => PAGES[tool.name]?.slug;
export const toolUrl = (publicUrl, tool) => `${publicUrl}/tools/${slugOf(tool)}`;

export function renderToolPage({ tool, tools, publicUrl }) {
  const p = PAGES[tool.name];
  const url = toolUrl(publicUrl, tool);
  const mcpUrl = `${publicUrl}/mcp`;
  const curl = `curl -X POST ${publicUrl}${tool.path} \\\n  -H "Content-Type: application/json" \\\n  -d '${JSON.stringify(tool.example)}'`;
  const cfg = JSON.stringify({ mcpServers: { "xonta-docs": { url: mcpUrl } } }, null, 2);
  const ld = [
    {
      "@context": "https://schema.org",
      "@type": "WebAPI",
      name: `${p.h1} — Xonta Документы`,
      description: p.desc,
      url,
      documentation: `${publicUrl}/openapi.json`,
      provider: { "@type": "Organization", name: "Xonta", url: "https://xonta.ru" },
      offers: { "@type": "Offer", price: "0", priceCurrency: "RUB" },
    },
    {
      "@context": "https://schema.org",
      "@type": "BreadcrumbList",
      itemListElement: [
        { "@type": "ListItem", position: 1, name: "Xonta Документы", item: `${publicUrl}/` },
        { "@type": "ListItem", position: 2, name: tool.title, item: url },
      ],
    },
    {
      "@context": "https://schema.org",
      "@type": "FAQPage",
      mainEntity: p.faq.map(([q, a]) => ({ "@type": "Question", name: q, acceptedAnswer: { "@type": "Answer", text: a } })),
    },
  ];
  const others = tools.filter((t) => t !== tool && slugOf(t));
  return `<!doctype html>
<html lang="ru"><head>
${headTags({ title: p.title, description: p.desc, url, publicUrl, ld })}
${STYLE}
</head><body><main>
${topNav()}
<p class="crumbs"><a href="/">Xonta Документы</a> › ${esc(tool.title)}</p>
<h1>${esc(p.h1)}</h1>
<p class="lead">${esc(p.intro)}</p>
<ul class="list">${p.points.map((x) => `<li>${esc(x)}</li>`).join("")}</ul>

<h2>Что делает инструмент</h2>
<p>${esc(tool.description)}</p>

<h2>Подключить по MCP</h2>
<p>Адрес сервера (Streamable HTTP), ключ не нужен. Имя инструмента: <code>${esc(tool.name)}</code>.</p>
<pre><code>${esc(cfg)}</code></pre>

<h2>Вызвать по HTTP</h2>
<pre><code>${esc(curl)}</code></pre>

<h2>Частые вопросы</h2>
${p.faq.map(([q, a]) => `<p><b>${esc(q)}</b> ${esc(a)}</p>`).join("\n")}

<h2>Другие инструменты</h2>
<ul class="list">${others.map((t) => `<li><a href="/tools/${slugOf(t)}">${esc(PAGES[t.name].h1)}</a></li>`).join("")}</ul>
${footer()}
</main></body></html>`;
}

export function mountSeo(app, { tools, publicUrl }) {
  const byslug = new Map(tools.filter(slugOf).map((t) => [slugOf(t), t]));
  app.get("/tools/:slug", (req, res) => {
    const t = byslug.get(req.params.slug);
    if (!t) return res.status(404).type("text/plain").send("Not found");
    res.type("html").set("Cache-Control", "public, max-age=3600").send(renderToolPage({ tool: t, tools, publicUrl }));
  });
  app.get("/robots.txt", (_req, res) =>
    res.type("text/plain").send(`User-agent: *\nAllow: /\nDisallow: /v1/\nDisallow: /mcp\nDisallow: /files/\n\nSitemap: ${publicUrl}/sitemap.xml\nHost: ${publicUrl}\n`),
  );
  const lastmod = new Date().toISOString().slice(0, 10);
  app.get("/sitemap.xml", (_req, res) => {
    const urls = [`${publicUrl}/`, ...[...byslug.keys()].map((s) => `${publicUrl}/tools/${s}`), `${publicUrl}/llms.txt`];
    res.type("application/xml").send(
      `<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n` +
        urls.map((u, i) => `<url><loc>${u}</loc><lastmod>${lastmod}</lastmod><priority>${i === 0 ? "1.0" : "0.8"}</priority></url>`).join("\n") +
        `\n</urlset>\n`,
    );
  });
  // Ключ IndexNow: файл /<key>.txt с самим ключом (задаётся INDEXNOW_KEY в .env)
  const key = process.env.INDEXNOW_KEY;
  if (key) app.get(`/${key}.txt`, (_req, res) => res.type("text/plain").send(key));
}

export function allUrls(tools, publicUrl) {
  return [`${publicUrl}/`, ...tools.filter(slugOf).map((t) => toolUrl(publicUrl, t))];
}
