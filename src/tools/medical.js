// Проверка текста карточки товара или рекламы: лекарства, медицинские изделия, БАД, медицинские услуги.
// Опирается на статьи 24 и 25 закона «О рекламе» (38-ФЗ) и на постановление Правительства № 821 от 02.07.2026
// о проверке карточек на маркетплейсах. Проверяет текст и формат номеров, но НЕ сверяет номера с реестрами
// и не является юридическим заключением.

const bad = (m) => Object.assign(new Error(m), { status: 400 });
const KINDS = { drug: "лекарственный препарат", device: "медицинское изделие", supplement: "БАД", service: "медицинская услуга" };

// ---------- номера регистрации ----------
const REG = [
  { kind: "device", title: "Регистрационное удостоверение на медизделие", re: /(?<![А-ЯЁA-Z])(РЗН|ФСР|ФСЗ)\s*((?:19|20)\d{2})\s*\/\s*(\d{3,6})/g },
  { kind: "drug", title: "Регистрационное удостоверение лекарственного препарата", re: /(?<![А-ЯЁA-Z])(ЛП|ЛСР|ЛС)\s?-\s?№?\s?\(?(\d{5,6})\)?(?:\s?-\s?\(?РГ-[A-Z]{2}\)?|\/\d{2}(?:-\d{4})?)?/g },
  { kind: "drug", title: "Регистрационное удостоверение лекарственного препарата (старый формат)", re: /(?<![А-ЯЁA-Z])([ПР])\s?N\s?(0\d{5})\/(\d{2})/g },
  { kind: "supplement", title: "Свидетельство о государственной регистрации (БАД)", re: /(?<![A-ZА-Я.])(RU|KZ|BY|AM|KG)\.(\d{2})\.(\d{2})\.(\d{2})\.(\d{3})\.([ЕEРRМM])\.(\d{6})\.(\d{2})\.(\d{2})(?!\d)(?!\.\d)/g },
];

function findRegistrations(text) {
  const out = [];
  for (const r of REG) {
    for (const m of text.matchAll(r.re)) {
      const item = { number: m[0].replace(/\s+/g, " ").trim(), kind: r.kind, title: r.title, format_ok: true };
      if (r.kind === "device" && Number(m[2]) > new Date().getFullYear()) { item.format_ok = false; item.problem = "год в номере больше текущего"; }
      if (r.kind === "supplement") {
        const month = Number(m[8]), year = Number(m[9]);
        if (month < 1 || month > 12) { item.format_ok = false; item.problem = `месяц выдачи «${m[8]}» вне диапазона 01–12`; }
        else item.issued = `${m[8]}.20${m[9]}`;
        if (year > Number(String(new Date().getFullYear()).slice(2))) { item.format_ok = false; item.problem = "год выдачи больше текущего"; }
      }
      out.push(item);
    }
  }
  return out;
}

// ---------- тип товара ----------
const KIND_HINTS = {
  supplement: /(?<![а-яё])БАД(?![а-яё])|биологически активн[а-яё]* добавк/iu,
  device: /медицинск[а-яё]* издели|тонометр|глюкометр|ингалятор|небулайзер|термометр|пульсоксиметр|ортопедическ|бандаж|компрессионн[а-яё]* (чулк|трикотаж)/iu,
  drug: /лекарственн[а-яё]* (препарат|средств)|(?<![а-яё])МНН(?![а-яё])|по рецепту|рецептурн|безрецептурн/iu,
  service: /клиник|медицинск[а-яё]* центр|при[её]м (врача|специалиста)|стоматолог|УЗИ|диагностик[а-яё]* (в|на)|процедур[а-яё]* в|лечение в|медицинск[а-яё]* услуг/iu,
};

function detectKind(text, regs) {
  if (regs.length) return { kind: regs[0].kind, by: "номер регистрации" };
  for (const k of ["supplement", "device", "drug", "service"]) if (KIND_HINTS[k].test(text)) return { kind: k, by: "ключевые слова" };
  return { kind: null, by: null };
}

// ---------- формулировки ----------
const A24 = "ст. 24 закона «О рекламе»", A25 = "ст. 25 закона «О рекламе»";
const RISKS = [
  { kinds: ["drug", "device", "service", "supplement"], re: /(помог|вылечил|избавил|излечил)[а-яё]*\s+(мне|меня|маме|папе|сыну|дочери|нам|бабушке|мужу|жене)|(?<![а-яё])(мне|меня|нам|маме|сыну|дочери)\s+(очень\s+)?(помог|вылечил|избавил)[а-яё]*|после (курса|при[её]ма|применения)[^.!?]{0,40}(прошл|исчез|забыл)/giu,
    why: "ссылка на конкретный случай излечения или улучшения здоровья", basis: { drug: `${A24}, ч. 1 п. 2`, supplement: `${A25}, ч. 1 п. 2` } },
  { kinds: ["drug", "device", "service", "supplement"], re: /(огромное |большое )?спасибо (за|вам|производител)|благодар[а-яё]+ (за|вам|производител|врач)/giu,
    why: "выражение благодарности от покупателей или пациентов", basis: { drug: `${A24}, ч. 1 п. 3`, supplement: `${A25}, ч. 1 п. 3` } },
  { kinds: ["drug", "device", "supplement"], re: /клинически (доказан|подтвержд|проверен)[а-яё]*|прош[её]л[а-я]* клинические (испытания|исследования)|эффективность доказана/giu,
    why: "ссылка на исследования как на преимущество (если это исследования, обязательные для регистрации)", basis: { drug: `${A24}, ч. 1 п. 4`, supplement: `${A25}, ч. 1 п. 5` } },
  { kinds: ["drug", "device"], re: /(у вас|вас беспокоит|вы страдаете|вас мучает|вам знакомы)[^.!?]{0,30}(бол|давлени|изжог|бессонниц|простуд|кашел|насморк|аллерги|диабет|суставы)/giu,
    why: "утверждение или предположение о заболевании у читателя", basis: { drug: `${A24}, ч. 1 п. 5` } },
  { kinds: ["drug", "device", "service", "supplement"], re: /без (врача|визита к врачу|обращения к врачу|консультации врача)|не нужно (идти|ходить|обращаться) к врачу|вместо (врача|похода к врачу)|заменит (врача|визит к врачу)/giu,
    why: "впечатление, что обращаться к врачу не нужно", basis: { drug: `${A24}, ч. 1 п. 7`, supplement: `${A25}, ч. 1 п. 1` } },
  { kinds: ["drug", "device", "service", "supplement"], re: /гарантир[а-яё]+ (результат|эффект|излечени|выздоровлени|безопасност)|100\s?%\s?(результат|эффект|излечени|гарантия)|абсолютно безопас[а-яё]*|полностью безопас[а-яё]*|без побочных (эффектов|действий)|не (имеет|вызывает) побочных/giu,
    why: "гарантия эффекта, безопасности или отсутствия побочных действий", basis: { drug: `${A24}, ч. 1 п. 8`, supplement: `${A25}, ч. 1 п. 1` } },
  { kinds: ["drug", "supplement"], re: /(натуральн|природн|растительн)[а-яё]*[^.!?]{0,40}(безопас|без вреда|не навредит|без последствий)/giu,
    why: "безопасность или эффективность объясняется натуральным происхождением", basis: { drug: `${A24}, ч. 1 п. 10`, supplement: `${A25}, ч. 1 п. 1` } },
  { kinds: ["supplement"], re: /(?<![а-яё])(лечит|лечение|лечебн[а-яё]*|излеч[а-яё]*|вылеч[а-яё]*|исцел[а-яё]*|терапи[а-яё]*)(?![а-яё])|(?<![а-яё])от (диабета|рака|онкологии|гипертонии|давления|простатита|паразитов|грибка|артрита|артроза|остеохондроза|варикоза|геморроя|цистита|гастрита)|(?<![а-яё])(лекарств[а-яё]*|препарат[а-яё]*)(?![а-яё])/giu,
    why: "впечатление, что БАД — лекарство или обладает лечебными свойствами", basis: { supplement: `${A25}, ч. 1 п. 1` } },
  { kinds: ["supplement"], re: /вместо (еды|питания|завтрака|обеда|ужина|овощей|фруктов)|заменяет (питание|еду|приём пищи)|можно не (соблюдать диету|есть)/giu,
    why: "побуждение к отказу от здорового питания", basis: { supplement: `${A25}, ч. 1 п. 4` } },
  { kinds: ["drug"], re: /(?<![а-яё])(БАД|биологически активн[а-яё]* добавк[а-яё]*|пищев[а-яё]* добавк[а-яё]*)(?![а-яё])/giu,
    why: "лекарство представлено как БАД или иной товар", basis: { drug: `${A24}, ч. 1 п. 9` } },
  { kinds: ["drug", "device", "service", "supplement"], re: /(?<![а-яё])(лучш[а-яё]+ (клиника|врачи|препарат|средство|добавка|в городе|в России)|№\s?1|номер один|самый эффективн[а-яё]*)/giu,
    why: "превосходная степень без подтверждения: может считаться недостоверным сравнением", basis: { any: "ст. 5 закона «О рекламе» (недостоверная реклама)" } },
];

const WARN_MED = /противопоказани|ознаком[а-яё]+ с инструкци|инструкци[а-яё]* по (применению|медицинскому применению)|консультаци[а-яё]* (со |с )?(специалист|врач)|проконсультир[а-яё]+ (со |с )?(специалист|врач)/iu;
const WARN_SUPP = /не является лекарств(ом|енным (средством|препаратом))/iu;

export async function checkMedicalText(args) {
  const text = String(args.text ?? "").trim();
  if (!text) throw bad("text: передайте текст карточки товара или рекламы");
  if (text.length > 30000) throw bad("text: не больше 30 000 символов");
  const channel = args.channel === "ad" ? "ad" : "card";
  const regs = findRegistrations(text);
  const declared = KINDS[args.kind] ? args.kind : null;
  const detected = detectKind(text, regs);
  const kind = declared || detected.kind;
  if (!kind) {
    return {
      kind: null,
      status: "тип не определён",
      verdict: "Не удалось понять, о каком товаре текст. Передайте kind: drug, device, supplement или service.",
      registrations: regs,
      disclaimer: DISCLAIMER,
    };
  }

  const problems = [], recommendations = [];
  // 1. Обязательное предупреждение
  const warning = kind === "supplement"
    ? { required: "«Не является лекарственным средством»", present: WARN_SUPP.test(text), basis: `${A25}, ч. 1.1`, size: "в рекламе — не менее 10% рекламной площади (на радио 3 с, на ТВ 5 с и 7% кадра)" }
    : { required: "о противопоказаниях, о необходимости ознакомиться с инструкцией или получить консультацию специалиста (достаточно одного)", present: WARN_MED.test(text), basis: `${A24}, ч. 7`, size: "в рекламе — не менее 5% рекламной площади (на радио 3 с, на ТВ 5 с и 7% кадра)" };
  if (!warning.present) (channel === "ad" ? problems : recommendations).push(`Нет предупреждения ${warning.required} (${warning.basis}).`);

  // 2. Рецептурные препараты в рекламе для всех
  if (kind === "drug" && channel === "ad" && /рецептурн|отпуска[её]тся по рецепту|по рецепту врача/iu.test(text) && !/безрецептурн|без рецепта/iu.test(text))
    problems.push("Похоже на рекламу рецептурного препарата: для широкой аудитории она не допускается (ст. 24 закона «О рекламе», ч. 8).");

  // 3. Рискованные формулировки
  const risky = [];
  // обязательные предупреждения не должны сами попадать в «рискованные» («не является лекарственным средством»)
  const scan = text.replace(new RegExp(WARN_SUPP.source, "giu"), " ").replace(/имеются противопоказания[^.!?]*/giu, " ");
  for (const r of RISKS) {
    if (!r.kinds.includes(kind)) continue;
    for (const m of scan.matchAll(r.re)) {
      const basis = r.basis[kind] || r.basis.drug || r.basis.any;
      if (!risky.some((x) => x.phrase.toLowerCase() === m[0].toLowerCase())) risky.push({ phrase: m[0], why: r.why, basis });
    }
  }

  // 4. Номер регистрации и поля карточки (постановление № 821)
  const regOfKind = regs.filter((x) => x.kind === kind);
  if (kind !== "service") {
    if (!regs.length) problems.push(`В тексте не найден номер регистрации (${kind === "supplement" ? "свидетельство о госрегистрации, например RU.77.99.32.003.R.001234.10.24" : kind === "device" ? "регистрационное удостоверение, например РЗН 2021/12345" : "регистрационное удостоверение, например ЛП-001234"}). С 1 октября 2026 года маркетплейсы сверяют его с госреестрами до публикации карточки.`);
    else if (!regOfKind.length) problems.push(`Найден номер другого типа (${regs.map((x) => x.title).join(", ")}), а товар похож на «${KINDS[kind]}» — проверьте, что указан нужный документ.`);
    for (const r of regs.filter((x) => !x.format_ok)) problems.push(`Номер ${r.number}: ${r.problem}.`);
    if (channel === "card" && kind !== "supplement" && regs.length) {
      if (!/\d{2}\.\d{2}\.\d{4}/.test(text)) recommendations.push("Укажите дату регистрации удостоверения: по постановлению № 821 в карточке должны быть номер, дата регистрации и срок действия.");
      if (!/срок действия|действительн[а-яё]* до|бессрочн/iu.test(text)) recommendations.push("Укажите срок действия регистрационного удостоверения (или «бессрочно»).");
    }
  }

  const status = problems.length || risky.length ? "есть замечания" : recommendations.length ? "есть рекомендации" : "замечаний не найдено";
  return {
    kind,
    kind_title: KINDS[kind],
    kind_source: declared ? "указан в запросе" : detected.by,
    channel: channel === "ad" ? "реклама" : "карточка товара",
    status,
    verdict:
      status === "замечаний не найдено"
        ? "По нашим правилам замечаний не найдено. Это не гарантирует прохождение модерации: номер регистрации нужно сверить с реестром."
        : `Найдено замечаний: ${problems.length + risky.length}, рекомендаций: ${recommendations.length}.`,
    problems,
    risky_phrases: risky,
    recommendations,
    required_warning: warning,
    registrations: regs,
    where_to_verify: {
      drug: "Государственный реестр лекарственных средств (ГРЛС): grls.rosminzdrav.ru",
      device: "Реестр медицинских изделий Росздравнадзора: roszdravnadzor.gov.ru, раздел «Электронные сервисы»",
      supplement: "Единый реестр свидетельств о государственной регистрации ЕАЭС (портал Евразийской экономической комиссии)",
    }[kind] || null,
    disclaimer: DISCLAIMER,
  };
}

const DISCLAIMER =
  "Это автоматическая подсказка по тексту, а не юридическое заключение. Сервис опирается на статьи 24 и 25 закона «О рекламе» и постановление Правительства № 821, " +
  "проверяет формат номеров регистрации, но не сверяет их с государственными реестрами и не оценивает размер шрифта предупреждений. Окончательное решение — за вами или вашим юристом.";
